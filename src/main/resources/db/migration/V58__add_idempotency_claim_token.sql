-- 멱등 선점 펜싱 토큰
--
-- 선점(claim)할 때마다 새 토큰을 기록하고, 완료·거절·해제는 자기가 받은 토큰과 일치할 때만 행을 바꾼다.
-- 리스(60초)가 끝나 다른 요청이 같은 키를 재선점한 뒤에 원래 요청이 늦게 도착해도,
-- 토큰이 달라 DONE 기록이 0건이 되고 주문 트랜잭션이 롤백된다. 이중 주문이 커밋되지 않는다.
--
-- 기존 행: 보존 기간 24시간짜리 기록이고 PROCESSING 행은 선점한 요청이 이미 끝났으므로 NULL 로 둔다.
-- NULL 토큰 행은 어떤 요청의 토큰과도 일치하지 않아, 리스 만료 후 재선점될 때 새 토큰을 받는다.
ALTER TABLE order_idempotency ADD COLUMN claim_token UUID;
